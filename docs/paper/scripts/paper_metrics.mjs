#!/usr/bin/env node
// Extracts the repo-derived numbers the paper cites, so every figure in the
// draft is reproducible from the tree rather than hand-copied.
//
//   node docs/paper/scripts/paper_metrics.mjs            # human-readable
//   node docs/paper/scripts/paper_metrics.mjs --tex      # LaTeX macro file
//   node docs/paper/scripts/paper_metrics.mjs --json     # machine-readable
//
// Writing the .tex output to docs/paper/generated/metrics.tex keeps the draft's
// \DefTestCount-style macros in sync with the code they describe.

import { readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const AI = join(ROOT, "supabase/functions/project-ai-chat");
const EVAL = join(AI, "eval");

const walk = (dir, out = []) => {
  if (!existsSync(dir)) return out;
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    statSync(p).isDirectory() ? walk(p, out) : out.push(p);
  }
  return out;
};
const lines = (p) => readFileSync(p, "utf8").split("\n").length;

// ---- deterministic-tier suite ------------------------------------------------
const testFiles = readdirSync(EVAL).filter((f) => f.endsWith("_test.ts"));
const perFile = testFiles
  .map((f) => ({
    file: f,
    cases: (readFileSync(join(EVAL, f), "utf8").match(/Deno\.test\(/g) ?? []).length,
  }))
  .sort((a, b) => b.cases - a.cases);
const testCases = perFile.reduce((s, r) => s + r.cases, 0);

// ---- golden fixtures ---------------------------------------------------------
const fixRoot = join(EVAL, "fixtures");
const suites = readdirSync(fixRoot)
  .filter((d) => statSync(join(fixRoot, d)).isDirectory())
  .map((d) => {
    const all = readdirSync(join(fixRoot, d)).filter((f) => f.endsWith(".json"));
    // corpora (verifier-corpus.json et al.) are inputs, not task fixtures
    const cases = all.filter((f) => !f.includes("corpus"));
    return { suite: d, fixtures: cases.length, support: all.length - cases.length };
  })
  .sort((a, b) => b.fixtures - a.fixtures);
const fixtureTotal = suites.reduce((s, r) => s + r.fixtures, 0);

// ---- routing golden set ------------------------------------------------------
const goldenPath = join(EVAL, "routing.golden.jsonl");
const goldenRows = existsSync(goldenPath)
  ? readFileSync(goldenPath, "utf8").split("\n").filter((l) => l.trim()).map((l) => {
      try { return JSON.parse(l); } catch { return null; }
    }).filter(Boolean)
  : [];
const goldenByClass = {};
for (const r of goldenRows) {
  const k = r.expect?.agent_id ?? r.expect?.intent ?? r.class ?? "unlabelled";
  goldenByClass[k] = (goldenByClass[k] ?? 0) + 1;
}
const goldenNeedsRun = goldenRows.filter((r) => r.expect?.needs_run === true).length;
const goldenCacheable = goldenRows.filter((r) => r.expect?.cache_checkable === true).length;

// ---- implementation size -----------------------------------------------------
const srcFiles = readdirSync(AI).filter((f) => f.endsWith(".ts"));
const srcLoc = srcFiles.reduce((s, f) => s + lines(join(AI, f)), 0);
const evalLoc = walk(EVAL).filter((f) => f.endsWith(".ts")).reduce((s, f) => s + lines(f), 0);
const biggest = srcFiles
  .map((f) => ({ file: f, loc: lines(join(AI, f)) }))
  .sort((a, b) => b.loc - a.loc)
  .slice(0, 12);

// ---- migrations backing the harness -----------------------------------------
const migDir = join(ROOT, "supabase/migrations");
const harnessMigrations = existsSync(migDir)
  ? readdirSync(migDir).filter((f) =>
      /agent|chat_plans|verifier|model_capability|proposal|telemetry|reports_and_file/i.test(f))
  : [];

// ---- design-doc size ---------------------------------------------------------
const designDoc = join(ROOT, "docs/design/ai-agents.md");
const designLines = existsSync(designDoc) ? lines(designDoc) : 0;

const M = {
  testFiles: testFiles.length,
  testCases,
  perFile,
  suites,
  fixtureTotal,
  goldenRows: goldenRows.length,
  goldenByClass,
  goldenNeedsRun,
  goldenCacheable,
  srcFiles: srcFiles.length,
  srcLoc,
  evalLoc,
  biggest,
  harnessMigrations,
  designLines,
};

const arg = process.argv[2];

if (arg === "--json") {
  console.log(JSON.stringify(M, null, 2));
} else if (arg === "--tex") {
  const mac = (name, val) => `\\newcommand{\\${name}}{${val}}`;
  console.log([
    "% Generated by docs/paper/scripts/paper_metrics.mjs -- do not edit by hand.",
    mac("TestCount", M.testCases),
    mac("TestFileCount", M.testFiles),
    mac("FixtureCount", M.fixtureTotal),
    mac("SuiteCount", M.suites.length),
    mac("GoldenRows", M.goldenRows),
    mac("HarnessLoc", M.srcLoc.toLocaleString("en-US")),
    mac("HarnessModules", M.srcFiles),
    mac("EvalLoc", M.evalLoc.toLocaleString("en-US")),
    mac("MigrationCount", M.harnessMigrations.length),
    mac("DesignLines", M.designLines.toLocaleString("en-US")),
  ].join("\n"));
} else {
  const pad = (s, n) => String(s).padEnd(n);
  console.log("\n=== SureSuite AI harness — paper metrics ===\n");
  console.log(`Deterministic tier : ${M.testCases} test cases across ${M.testFiles} files`);
  console.log(`Golden fixtures    : ${M.fixtureTotal} across ${M.suites.length} suites`);
  console.log(`Routing golden set : ${M.goldenRows} labelled utterances`);
  console.log(`                     needs_run=${M.goldenNeedsRun}, cache_checkable=${M.goldenCacheable}`);
  console.log(`Harness impl       : ${M.srcLoc.toLocaleString()} LOC (${M.srcFiles} modules)`);
  console.log(`Eval harness       : ${M.evalLoc.toLocaleString()} LOC`);
  console.log(`Backing migrations : ${M.harnessMigrations.length}`);
  console.log(`Design spec        : ${M.designLines.toLocaleString()} lines\n`);

  console.log("--- fixtures per suite ---");
  for (const s of M.suites) console.log(`  ${pad(s.suite, 24)} ${s.fixtures}`);

  console.log("\n--- largest harness modules ---");
  for (const b of M.biggest) console.log(`  ${pad(b.file, 24)} ${b.loc}`);

  console.log("\n--- routing golden set by expected class ---");
  for (const [k, v] of Object.entries(M.goldenByClass).sort((a, b) => b[1] - a[1])) {
    console.log(`  ${pad(k, 24)} ${v}`);
  }
  console.log();
}
