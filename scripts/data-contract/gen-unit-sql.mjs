#!/usr/bin/env node
// Render the SQL unit table FROM the canonical TypeScript one (Phase 1 / WP 1.3, D10).
//
//   npm run contract:units            # (re)write the generated SQL
//   npm run contract:units -- --check # CI gate
//
// There is exactly one UNIT_DAYS in this repo: `UNIT_DAYS` in
// supabase/functions/_shared/grading.ts. `effectiveEconomics.ts` imports it,
// `_shared/laneVolumes.ts` imports it, `project_map.py::_UNIT_DAYS` mirrors it
// key for key under a parity test — and SQL now GENERATES from it rather than
// restating it.
//
// Restating it is what D10 was. The `sc_nodes` view carried its own conversion as
// three ILIKE branches and an ELSE:
//
//     WHEN time_unit ILIKE '%day%'   THEN volume * 7.0
//     WHEN time_unit ILIKE '%month%' THEN volume / 4.345
//     WHEN time_unit ILIKE '%year%'  THEN volume / 52.18
//     ELSE volume
//
// A row quoted in QUARTERS matches none of them, falls to ELSE, and is treated as
// weekly — thirteen times its real value. `quarterly` also matches nothing.
// Meanwhile 4.345 and 52.18 are not 30.4375/7 and 365.25/7, so even the branches
// that hit disagreed with the engine in the fourth significant figure.
//
// The generator reads the table out of the TypeScript source rather than keeping a
// second copy here, so this file cannot drift either.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const CANON = join(ROOT, "supabase", "functions", "_shared", "grading.ts");
const OUT = join(ROOT, "supabase", "migrations", "20260915000001_one_unit_table.sql");

/** Read UNIT_DAYS out of grading.ts without executing TypeScript. */
export function readUnitDays() {
  const src = readFileSync(CANON, "utf8");
  const start = src.indexOf("export const UNIT_DAYS");
  if (start === -1) throw new Error("UNIT_DAYS not found in grading.ts — the canonical table moved");
  const open = src.indexOf("{", start);
  const close = src.indexOf("};", open);
  if (open === -1 || close === -1) throw new Error("UNIT_DAYS literal is not a plain object — update this parser");
  const body = src.slice(open + 1, close);

  const table = new Map();
  for (const entry of body.split(",")) {
    const m = /^\s*([A-Za-z_][\w]*|"[^"]+"|'[^']+')\s*:\s*([0-9.]+)\s*$/.exec(entry);
    if (!m) {
      if (entry.trim()) throw new Error(`UNIT_DAYS entry not understood: ${entry.trim()}`);
      continue;
    }
    table.set(m[1].replace(/^["']|["']$/g, ""), m[2]);
  }
  if (table.size === 0) throw new Error("UNIT_DAYS parsed as empty");
  return table;
}

function render(table) {
  const whens = [...table.entries()]
    .map(([unit, days]) => `    WHEN '${unit}' THEN ${days}::numeric`)
    .join("\n");

  return `-- GENERATED by scripts/data-contract/gen-unit-sql.mjs from
-- supabase/functions/_shared/grading.ts::UNIT_DAYS. Do not edit by hand: the data
-- contract CI gate (\`npm run contract:units -- --check\`) fails on drift.
--
-- Phase 1 / WP 1.3 / D10 — ONE unit table.
--
-- Before this migration the platform carried three conversions that disagreed.
-- The third lived in the \`sc_nodes\` view as three ILIKE branches and an ELSE, so
-- a row quoted in QUARTERS matched nothing, fell to ELSE and was read as weekly:
-- a 13x error on that product's demand, silently. Its constants (4.345, 52.18)
-- also disagreed with the canonical 30.4375/7 and 365.25/7.
--
-- \`unit_days\` below is rendered from the TypeScript table; SQL no longer holds an
-- opinion about what a quarter is.

CREATE OR REPLACE FUNCTION public.unit_days(unit text)
RETURNS numeric
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = public
AS $$
  SELECT CASE lower(btrim(coalesce(unit, '')))
${whens}
    ELSE NULL::numeric
  END;
$$;

COMMENT ON FUNCTION public.unit_days(text) IS
  'Days in one period of \`unit\`, or NULL when the unit is unrecognised. Generated '
  'from grading.ts::UNIT_DAYS — the one unit table (PLAN.md §4 D10, invariant I3).';

-- Quantity per \`unit\`-period -> quantity per week. Mirrors
-- grading.ts::rateToWeekly and project_map.py::_rate_to_weekly, including the
-- default: an unrecognised or missing unit is read on a 7-day basis, i.e. the
-- value is already weekly.
CREATE OR REPLACE FUNCTION public.rate_to_weekly(value numeric, unit text, default_days numeric DEFAULT 7)
RETURNS numeric
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = public
AS $$
  SELECT value * 7.0 / COALESCE(NULLIF(public.unit_days(unit), 0), default_days);
$$;

COMMENT ON FUNCTION public.rate_to_weekly(numeric, text, numeric) IS
  'A rate quoted per \`unit\` expressed per week. Mirrors grading.ts::rateToWeekly.';

-- A DURATION of \`value\` \`unit\`s expressed in weeks. Mirrors
-- project_map.py::_duration_to_weeks. Note the direction: a duration of 1 month
-- is ~4.35 weeks, while a rate of 1 per month is ~0.23 per week.
CREATE OR REPLACE FUNCTION public.duration_to_weeks(value numeric, unit text, default_days numeric DEFAULT 7)
RETURNS numeric
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = public
AS $$
  SELECT value * COALESCE(NULLIF(public.unit_days(unit), 0), default_days) / 7.0;
$$;

COMMENT ON FUNCTION public.duration_to_weeks(numeric, text, numeric) IS
  'A duration of \`value\` \`unit\`s expressed in weeks. Mirrors project_map.py::_duration_to_weeks.';

GRANT EXECUTE ON FUNCTION public.unit_days(text) TO authenticated, anon, service_role;
GRANT EXECUTE ON FUNCTION public.rate_to_weekly(numeric, text, numeric) TO authenticated, anon, service_role;
GRANT EXECUTE ON FUNCTION public.duration_to_weeks(numeric, text, numeric) TO authenticated, anon, service_role;

-- ── sc_nodes: delegate, and weight the price aggregate the way the engine does ──
--
-- Two changes, both to the \`agg\` sub-select:
--
--   1. weekly_demand calls rate_to_weekly() instead of restating the table.
--   2. the price aggregate now matches grading.ts::demandWeightedSellPrice:
--      weight by WEEKLY volume (not raw volume, which mixes periods exactly as
--      D2 did), skip rows with no price rather than averaging a zero in, and
--      drop the \`ELSE MAX(unit_price)\` fallback. MAX() is not an estimate of
--      anything — for a product sold to three customers at 8, 10 and 30 with no
--      volumes, it answered 30.
CREATE OR REPLACE VIEW public.sc_nodes AS
SELECT 'supplier:' || s.supplier_id AS id, s.project_id, COALESCE(s.name, s.supplier_id) AS name,
       'supplier' AS node_type, NULL::numeric AS weekly_demand, NULL::numeric AS unit_price,
       NULL::numeric AS capacity_units_per_day, 1.0::numeric AS yield_rate,
       s.capacity_per_week
FROM public.suppliers s
UNION ALL
SELECT 'material:' || m.material_id, m.project_id, COALESCE(m.name, m.material_id),
       'material', NULL::numeric, m.cost, NULL::numeric, 1.0::numeric, NULL::numeric
FROM public.materials m
UNION ALL
SELECT 'product:' || p.product_id, p.project_id, COALESCE(p.name, p.product_id),
       'product',
       COALESCE(p.demand_mean, agg.weekly_demand),
       COALESCE(p.sell_price, agg.unit_price),
       p.production_capacity, 1.0::numeric, NULL::numeric
FROM public.products p
LEFT JOIN (
  SELECT project_id, product_id,
         SUM(public.rate_to_weekly(COALESCE(volume, 0), time_unit)) AS weekly_demand,
         CASE
           WHEN SUM(CASE WHEN COALESCE(unit_price, 0) <> 0
                         THEN GREATEST(public.rate_to_weekly(COALESCE(volume, 0), time_unit), 1e-9)
                         ELSE 0 END) > 0
           THEN SUM(CASE WHEN COALESCE(unit_price, 0) <> 0
                         THEN unit_price * GREATEST(public.rate_to_weekly(COALESCE(volume, 0), time_unit), 1e-9)
                         ELSE 0 END)
              / SUM(CASE WHEN COALESCE(unit_price, 0) <> 0
                         THEN GREATEST(public.rate_to_weekly(COALESCE(volume, 0), time_unit), 1e-9)
                         ELSE 0 END)
           ELSE NULL::numeric
         END AS unit_price
  FROM public.outbound_logistics GROUP BY project_id, product_id
) agg ON agg.project_id = p.project_id AND agg.product_id = p.product_id
UNION ALL
SELECT 'customer:' || o.customer_id, o.project_id, o.customer_id,
       'customer', NULL::numeric, NULL::numeric, NULL::numeric, 1.0::numeric, NULL::numeric
FROM public.outbound_logistics o GROUP BY o.project_id, o.customer_id;

GRANT SELECT ON public.sc_nodes TO authenticated, anon, service_role;
`;
}

const sql = render(readUnitDays());
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
  if (current !== sql) {
    console.error(
      `UNIT DRIFT: ${relative(ROOT, OUT)} no longer matches grading.ts::UNIT_DAYS — ` +
      "run `npm run contract:units` and commit.",
    );
    process.exit(1);
  }
  console.log("✓ the SQL unit table matches grading.ts::UNIT_DAYS");
  process.exit(0);
}
writeFileSync(OUT, sql);
console.log(`✓ ${relative(ROOT, OUT)} rendered from grading.ts::UNIT_DAYS`);
