#!/usr/bin/env node
/**
 * Build the SuReSuite Python notebooks — `npm run notebooks:build`
 * (and `-- --check`, which `npm run lint` and CI run).
 *
 * ── WHY THE NOTEBOOKS ARE GENERATED ─────────────────────────────────────────
 *
 * A notebook reaches a user as ONE file: downloaded from `/developer` and
 * uploaded to Colab, or opened in a local Jupyter. It cannot import a shared
 * module (the repository is private), so the client every notebook needs has to
 * be INSIDE each one. Five hand-kept copies of one client is the defect the
 * single-source rule (I1) exists to stop, so the copies are made by this script
 * from one source and the committed files are compared against it.
 *
 *   notebooks/src/NN_<name>.py          percent-format sources (`# %%` cells)
 *   notebooks/src/common/*.py           the shared cells, included by marker
 *   notebooks/demo/example_project.json recorded engine output (record_demo.py)
 *   src/lib/sim/kpiDisplay.ts           KPI labels, formats and directions
 *     → python/suresuite/kpi_display.py        (generated; the package imports it)
 *     → public/notebooks/suresuite_NN_<name>.ipynb
 *
 * Cell markers in a source:
 *   # %%                          a code cell
 *   # %% [markdown]               a markdown cell (each line starts with "# ")
 *   # %% include: config|setup|library|local
 *   # %% include: demo_data <label> <label> …   the recordings the notebook replays
 *
 * ── WHAT --check REFUSES ───────────────────────────────────────────────────
 *
 *  · a committed notebook (or kpi_display.py) that differs from what the
 *    sources produce, or a notebook in public/notebooks/ no source produces;
 *  · a CONFIG cell whose variables differ from the ones `/developer` writes
 *    when it pre-fills a download (`nbConfigCell` in DeveloperApi.tsx);
 *  · a notebook `/developer` offers that is not built here, or the reverse;
 *  · an emoji (the product's copy rule, same ranges as scripts/audit-adaptive-ui.mjs);
 *  · a file:line citation — PLAN.md §4 owns data-layer evidence (I1), and a
 *    customer cannot open a private repository's line numbers anyway;
 *  · the run status `succeeded` (runs finish `done`), and a disruption target
 *    of a kind the engine skips (material, edge, customer, lane — §4 D112).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateRawSync, inflateRawSync } from "node:zlib";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SRC = join(ROOT, "notebooks", "src");
const OUT = join(ROOT, "public", "notebooks");
const DEMO = join(ROOT, "notebooks", "demo", "example_project.json");
const KPI_TS = join(ROOT, "src", "lib", "sim", "kpiDisplay.ts");
const PKG = join(ROOT, "python", "suresuite");
const KPI_PY = join(PKG, "kpi_display.py");
const DEV_PAGE = join(ROOT, "src", "pages", "DeveloperApi.tsx");
const CHECK = process.argv.includes("--check");

const read = (p) => readFileSync(p, "utf8");
const problems = [];

// ── KPI display vocabulary, from the app's one catalog ─────────────────────
function kpiDisplayPy() {
  const src = read(KPI_TS);
  const body = src.slice(src.indexOf("export const KPI_DISPLAY"), src.indexOf("export const KPI_ORDER"));
  const re = /\{\s*key:\s*"([^"]+)",\s*label:\s*"([^"]+)",\s*format:\s*(pct1|pct2|money|units|fixed\((\d)\)),\s*higherIsBetter:\s*(true|false|null)/g;
  const rows = [];
  for (const m of body.matchAll(re)) {
    const fmt = m[4] ? `fixed${m[4]}` : m[3];
    const dir = { true: "True", false: "False", null: "None" }[m[5]];
    rows.push(`    ${JSON.stringify(m[1])}: (${JSON.stringify(m[2])}, ${JSON.stringify(fmt)}, ${dir}),`);
  }
  const declared = (body.match(/\{\s*key:\s*"/g) || []).length;
  if (rows.length !== declared || rows.length < 20) {
    throw new Error(
      `kpiDisplay.ts: matched ${rows.length} of ${declared} KPI_DISPLAY entries — the literal's shape changed; fix the scan`,
    );
  }
  return [
    "# GENERATED by scripts/notebooks/build-notebooks.mjs from src/lib/sim/kpiDisplay.ts — do not edit.",
    "# The Simulation Lab's KPI vocabulary: key → (label, format, higher_is_better).",
    "# higher_is_better is None where \"better\" is not defined (inventory, utilization).",
    "KPI_DISPLAY = {",
    ...rows,
    "}",
    "",
  ].join("\n");
}

// ── demo data: only the recordings a notebook replays, compressed ──────────
const demo = JSON.parse(read(DEMO));
function demoCell(labels) {
  const recs = labels.map((l) => {
    const r = demo.recordings.find((x) => x.label === l);
    if (!r) throw new Error(`demo_data: no recording labelled "${l}" in notebooks/demo/example_project.json`);
    return r;
  });
  const payload = { ...demo, recordings: recs };
  const b64 = deflateRawSync(Buffer.from(JSON.stringify(payload)), { level: 9 }).toString("base64");
  return [
    "# ── DEMO DATA ───────────────────────────────────────────────────────────────",
    `# Recorded engine output (scsim ${demo._provenance.engine_version}) for the Example project, replayed`,
    "# when no API key is found. Recorded by notebooks/tools/record_demo.py; not used in live mode.",
    `# Recordings: ${labels.join(", ")}.`,
    `DEMO_DATA = "${b64}"`,
  ].join("\n");
}
const decodeDemo = (text) => {
  const m = /DEMO_DATA = "([^"]*)"/.exec(text);
  return m ? inflateRawSync(Buffer.from(m[1], "base64")).toString("utf8") : null;
};

// ── percent-format source → nbformat 4.5 ────────────────────────────────────
const kpiPy = kpiDisplayPy();
const INCLUDES = {
  config: { title: "Configuration", text: () => read(join(SRC, "common", "config.py")) },
  setup: { title: "Setup: packages and API key", text: () => read(join(SRC, "common", "setup.py")), form: true },
  library: {
    title: "SuReSuite notebook library (run it; no need to read it)",
    text: () => `${read(join(PKG, "client.py")).trimEnd()}\n\n\n${kpiPy}`,
    form: true,
  },
  // Phase 12 · WP 12.6 — the package's local-simulation module, for the notebook
  // that runs the engine on the user's own machine.
  local: {
    title: "Local simulation (the suresuite package's local.py)",
    text: () => read(join(PKG, "local.py")),
    form: true,
  },
};

const lines = (s) => {
  const ls = s.replace(/\s+$/, "").split("\n");
  return ls.map((l, i) => (i < ls.length - 1 ? `${l}\n` : l));
};

function build(file) {
  const nn = file.slice(0, 2);
  const text = read(join(SRC, file));
  const chunks = text.split(/^(?=# %%)/m).filter((c) => c.trim());
  const cells = [];
  for (const chunk of chunks) {
    const [header, ...rest] = chunk.split("\n");
    const body = rest.join("\n").replace(/^\s*\n/, "").replace(/\s+$/, "");
    let cell;
    if (header.trim() === "# %% [markdown]") {
      const md = rest.map((l, i) => {
        if (l === "#") return "";
        if (l.startsWith("# ")) return l.slice(2);
        if (l.trim() === "") return "";
        throw new Error(`${file}: markdown line ${i + 1} of a cell does not start with "# ": ${l}`);
      });
      cell = { cell_type: "markdown", metadata: {}, source: lines(md.join("\n").trim()) };
    } else if (header.startsWith("# %% include:")) {
      const [name, ...args] = header.slice("# %% include:".length).trim().split(/\s+/);
      if (name === "demo_data") {
        cell = { cell_type: "code", metadata: { cellView: "form" }, source: lines(`# @title Demo data (recorded engine output)\n${demoCell(args)}`) };
      } else {
        const inc = INCLUDES[name];
        if (!inc) throw new Error(`${file}: unknown include "${name}"`);
        const src = inc.form ? `# @title ${inc.title}\n${inc.text()}` : inc.text();
        cell = { cell_type: "code", metadata: inc.form ? { cellView: "form" } : {}, source: lines(src) };
      }
      if (body) throw new Error(`${file}: an include line takes no body (found: ${body.slice(0, 40)}…)`);
    } else if (header.trim() === "# %%") {
      cell = { cell_type: "code", metadata: {}, source: lines(body) };
    } else {
      throw new Error(`${file}: unrecognised cell header: ${header}`);
    }
    if (cell.cell_type === "code") Object.assign(cell, { execution_count: null, outputs: [] });
    cells.push({ id: `nb${nn}-${String(cells.length).padStart(2, "0")}`, ...cell });
  }
  const titleCell = cells.find((c) => c.cell_type === "markdown");
  const title = (titleCell?.source[0] ?? "").replace(/^#\s*/, "").trim();
  const nb = {
    cells,
    metadata: {
      colab: { name: title, provenance: [] },
      kernelspec: { display_name: "Python 3", language: "python", name: "python3" },
      language_info: { name: "python" },
    },
    nbformat: 4,
    nbformat_minor: 5,
  };
  return { name: `suresuite_${file.replace(/\.py$/, "")}.ipynb`, text: `${JSON.stringify(nb, null, 1)}\n`, nb };
}

// ── content rules over everything a user will read ─────────────────────────
const ALLOWED_MARKS = /[▲▼›▸▾≈⚠→←·—✕↑↓✓✗○●◦⌈⌉⌊⌋]/g;
const EMOJI = /[\u{1F300}-\u{1FAFF}\u{1F900}-\u{1F9FF}\u{2300}-\u{23FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE0F}]/gu;
function lint(name, nb) {
  nb.cells.forEach((c, i) => {
    const src = c.source.join("").replace(/DEMO_DATA = "[^"]*"/, "");
    const where = `${name} cell ${i}`;
    const emoji = src.replace(ALLOWED_MARKS, "").match(EMOJI);
    if (emoji) problems.push(`${where}: emoji ${[...new Set(emoji)].join(" ")} (product copy rule)`);
    const cite = src.match(/\b[\w./-]+\.(?:ts|tsx|py|sql|mjs):\d+/);
    if (cite) problems.push(`${where}: file:line citation "${cite[0]}" — §4 owns that evidence, and the repo is private`);
    if (/\bsucceeded\b/.test(src)) problems.push(`${where}: "succeeded" — a run finishes with status "done"`);
    const bad = src.match(/target_type"?\s*[:=]\s*"(material|edge|customer|lane)"|"target"\s*:\s*"(material|edge|customer|lane):/);
    if (bad) problems.push(`${where}: a ${bad[1] || bad[2]} disruption target — the engine skips it (§4 D112)`);
  });
}

// ── parity with what /developer offers and pre-fills ────────────────────────
function developerParity(built) {
  const page = read(DEV_PAGE);
  const offered = new Set([...page.matchAll(/["'`]\/notebooks\/([A-Za-z0-9._-]+\.ipynb)["'`]/g)].map((m) => m[1]));
  const names = new Set(built.map((b) => b.name));
  for (const n of names) if (!offered.has(n)) problems.push(`/developer does not offer ${n} (add it to NOTEBOOKS in DeveloperApi.tsx)`);
  for (const n of offered) if (!names.has(n)) problems.push(`/developer offers /notebooks/${n}, which no source in notebooks/src builds`);

  const cfgVars = new Set([...read(join(SRC, "common", "config.py")).matchAll(/^([A-Z_]+) = /gm)].map((m) => m[1]));
  const start = page.indexOf("const nbConfigCell");
  const block = start >= 0 ? page.slice(start, page.indexOf("]);", start)) : "";
  const pageVars = new Set([...block.matchAll(/[`'"]([A-Z_]{3,}) = /g)].map((m) => m[1]));
  const same = cfgVars.size === pageVars.size && [...cfgVars].every((v) => pageVars.has(v));
  if (!same) {
    problems.push(
      `CONFIG drift: the notebooks declare {${[...cfgVars].join(", ")}} and /developer pre-fills ` +
        `{${[...pageVars].join(", ")}} (nbConfigCell in DeveloperApi.tsx)`,
    );
  }
  if (!read(join(SRC, "common", "config.py")).startsWith("# ── CONFIG")) {
    problems.push("config.py must start with the \"# ── CONFIG\" marker /developer patches");
  }
}

// ── main ───────────────────────────────────────────────────────────────────
const sources = readdirSync(SRC).filter((f) => /^\d\d_[a-z0-9_]+\.py$/.test(f)).sort();
const built = sources.map(build);
built.forEach((b) => lint(b.name, b.nb));
developerParity(built);

const wanted = new Set(built.map((b) => b.name));
const stale = readdirSync(OUT).filter((f) => f.endsWith(".ipynb") && !wanted.has(f));

if (CHECK) {
  if (!existsSync(KPI_PY) || read(KPI_PY) !== kpiPy) problems.push("python/suresuite/kpi_display.py is stale — run npm run notebooks:build");
  for (const b of built) {
    const path = join(OUT, b.name);
    const cur = existsSync(path) ? read(path) : null;
    if (cur === b.text) continue;
    // The compressed payload can differ byte-for-byte between zlib builds while
    // carrying the same data; compare what it decodes to before calling it drift.
    const strip = (t) => t.replace(/DEMO_DATA = \\"[^"\\]*\\"/, "DEMO_DATA");
    if (cur && strip(cur) === strip(b.text) && decodeDemo(JSON.parse(cur).cells.map((c) => c.source.join("")).join("\n")) === decodeDemo(b.nb.cells.map((c) => c.source.join("")).join("\n"))) continue;
    problems.push(`public/notebooks/${b.name} is stale — run npm run notebooks:build`);
  }
  for (const f of stale) problems.push(`public/notebooks/${f} is built by no source in notebooks/src — delete it or add its source`);
} else {
  writeFileSync(KPI_PY, kpiPy);
  for (const b of built) writeFileSync(join(OUT, b.name), b.text);
  for (const f of stale) console.warn(`note: public/notebooks/${f} is built by no source — delete it`);
  console.log(`built ${built.length} notebooks: ${built.map((b) => `${b.name} (${(b.text.length / 1024).toFixed(0)} KB)`).join(", ")}`);
}

if (problems.length) {
  console.error(`notebooks: ${problems.length} problem(s)\n${problems.map((p) => `  - ${p}`).join("\n")}`);
  process.exit(1);
}
if (CHECK) console.log(`notebooks: ${built.length} notebooks current, CONFIG in step with /developer, content rules clean`);
